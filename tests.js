const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('app.js', 'utf8').split('const $=')[0];
const context = vm.createContext({});
vm.runInContext(source + '\nthis.parse = parseMarkdown; this.example = EXAMPLE;', context);
let result = context.parse(context.example);
assert.equal(result.entities.length, 3);
assert.equal(result.warnings.length, 0);
assert.equal(result.entities[1].fields[1].fk.entity, 'Student');
result = context.parse('## Student\n- student_id INT PK\n## Enrollment\n- student_id INT PK, FK (Student.student_id)');
assert.equal(result.entities[1].fields[0].pk, true);
assert.equal(result.entities[1].fields[0].fk.field, 'student_id');
result = context.parse('* **`[Entity]` Student**\n* `🔑 student_id` (PK)\n* **`[Junction Table]` Enrollment** (Resolves $N:M$)\n* `🔗 student_id` (FK $\\rightarrow$ Student.student_id)\n* *Relationship:* Has many **Enrollments** (`1 : N`)');
assert.equal(result.entities.length, 2);
assert.equal(result.entities[1].fields.length, 1);
assert.equal(result.entities[1].fields[0].fk.entity, 'Student');
result = context.parse('## Test\n- id INT PK\n- id INT\n- parent INT FK -> Missing.id');
assert.equal(result.warnings.length, 2);
assert.equal(context.parse('```markdown\n## Ignored\n- id INT\n```').entities.length, 0);
result = context.parse('| Entity | Attribute | Type | Constraints |\n|---|---|---|---|\n| **Student** | `id` | INT | PK |\n| | `name` | VARCHAR | NOT NULL |');
assert.equal(result.entities[0].fields.length, 2);
console.log('All parser checks passed.');
vm.runInContext('this.separate=separateTables;this.overlaps=overlaps;this.height=height;this.sequence=connectedSequence;',context);
const tenant=context.parse(fs.readFileSync('examples/tenant-database-schema.md','utf8'));
const positions=Object.fromEntries(tenant.entities.map(e=>[e.name,{x:0,y:0}]));
context.separate(tenant.entities,positions);
function checkSpacing(){for(let i=0;i<tenant.entities.length;i++)for(let j=i+1;j<tenant.entities.length;j++){const a=tenant.entities[i],b=tenant.entities[j];assert.equal(context.overlaps({...positions[a.name],h:context.height(a)},{...positions[b.name],h:context.height(b)}),false,`${a.name} overlaps ${b.name}`);}}
checkSpacing();
const stable=JSON.stringify(positions);context.separate(tenant.entities,positions);assert.equal(JSON.stringify(positions),stable);
tenant.entities[0].fields.push(...Array.from({length:30},()=>({name:'growth'})));
context.separate(tenant.entities,positions);checkSpacing();
const graph=context.parse('## A\n- id INT PK\n- b INT FK -> B.id\n## B\n- id INT PK\n- c INT FK -> C.id\n## C\n- id INT PK\n- a INT FK -> A.id\n## Branch\n- a INT FK -> A.id\n## Isolated\n- id INT PK\n- missing INT FK -> Missing.id');
assert.deepEqual([...context.sequence(graph.entities,'B')].sort(),['A','B','Branch','C']);
assert.deepEqual([...context.sequence(graph.entities,'Isolated')],['Isolated']);
console.log('Spacing checks passed for 19 overlapping tables, field growth, and stable layouts; graph checks passed for branches, cycles, and disconnected entities.');
vm.runInContext('this.search=searchSchema;',context);
const searchModel=context.parse(context.example).entities;
assert.equal(context.search(searchModel,'  STUDENT  ').length,2);
assert.equal(context.search(searchModel,'email')[0].name,'Student');
assert.equal(context.search(searchModel,'email')[0].fields[0],'email');
assert.equal(context.search(searchModel,'not_found').length,0);
assert.equal(context.search(searchModel,'   ').length,0);
console.log('Search checks passed: table names, column names, case, whitespace, and no results.');
